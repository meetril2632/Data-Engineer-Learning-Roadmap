# Print Statement - "#" single line comment, {""" """}
print("Hello World")

# Single inverted comma ' ' or Double inverted comma " " same output when printing or passing values.
# Print with separator. Actually separates for multiple passed entities
print("I am Meet Poshia", 123, 'LMAO', sep="$")

# If you want to run multi-line print code this is how you do it
print("""I am Meet Poshia, How are ya?"
Let's go to the coffee shop.""")

# Escape the character or string using 'Meet Poshia' or using backslash \
print("I am 'Meet Poshia'. How are ya?")
print("I am \'Meet Poshia\'. How are ya?")